// Regenerates src/lib/abi.ts from Foundry build output. Run `forge build` in ../contracts first.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const read = (name) => JSON.parse(readFileSync(join(out, `${name}.sol/${name}.json`), "utf8")).abi;

const body = `// AUTO-GENERATED by scripts/export-abi.mjs — do not edit by hand.
export const gameTokenFactoryAbi = ${JSON.stringify(read("GameTokenFactory"), null, 2)} as const;

export const gameTokenAbi = ${JSON.stringify(read("GameToken"), null, 2)} as const;

export const prizePoolAbi = ${JSON.stringify(read("PrizePool"), null, 2)} as const;
`;
writeFileSync(join(here, "../src/lib/abi.ts"), body);
console.log("wrote src/lib/abi.ts");
