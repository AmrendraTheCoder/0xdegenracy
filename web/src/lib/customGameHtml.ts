import type { GameConfig } from "./game-config";

/**
 * Builds the self-contained HTML document an AI-written game runs in.
 *
 * Isolation model (defence in depth):
 *  1. The page embeds it in <iframe sandbox="allow-scripts"> WITHOUT allow-same-origin, so it gets an
 *     opaque origin: no access to our DOM, cookies, localStorage, wallet provider or Supabase session.
 *  2. A strict CSP (header on the live route, <meta> for the pre-launch preview) blocks all network:
 *     connect-src/default-src 'none'. Only inline script/style and https/data images (the face) load.
 *  3. Code is generated by our server, statically checked, and HMAC-signed before it can be launched.
 *
 * The runtime below is a small version of games/engine.ts: loop, input, HUD, start/game-over screens and
 * the same `api` helpers the presets use. It talks to the parent only through postMessage events
 * ({ source: "degen-game", type: "start" | "over" | "error" | "phase", ... }) and accepts key, pause
 * and restart messages back.
 */

// 'unsafe-eval' lets the runtime compile the game source from a JSON string (so the source can never break out
// of a <script> tag). It grants nothing extra here: the code is arbitrary JS anyway, and it stays confined to
// an opaque origin with no network, no storage and no access to the parent page.
export const CUSTOM_GAME_CSP =
  "default-src 'none'; script-src 'unsafe-inline' 'unsafe-eval'; style-src 'unsafe-inline'; img-src https: data:; font-src 'none'; connect-src 'none'; media-src 'none'; object-src 'none'; frame-src 'none'; worker-src 'none'; base-uri 'none'; form-action 'none'";

/** Safe to embed inside <script>: JSON with "<", ">" and "&" escaped so nothing can close the tag. */
const jsonForScript = (v: unknown) => JSON.stringify(v).replace(/</g, "\\u003c").replace(/>/g, "\\u003e").replace(/&/g, "\\u0026");

export function buildGameFrameHtml(opts: { code: string; cfg: GameConfig; imageUrl: string; withCspMeta?: boolean }): string {
  const { cfg } = opts;
  const publicCfg = {
    title: cfg.title,
    ticker: cfg.ticker,
    scoreLabel: cfg.scoreLabel,
    gameOverText: cfg.gameOverText,
    obstacleLabel: cfg.obstacleLabel,
    goodItemLabel: cfg.goodItemLabel,
    colors: cfg.colors,
    difficulty: cfg.difficulty,
  };
  // The game source is placed in a JSON string and compiled at runtime inside the sandbox, so its text can
  // never break out of the <script> element no matter what it contains.
  const boot = `window.__CFG__=${jsonForScript(publicCfg)};window.__IMG__=${jsonForScript(opts.imageUrl)};window.__SRC__=${jsonForScript(opts.code)};`;
  return `<!doctype html><html><head><meta charset="utf-8">
${opts.withCspMeta ? `<meta http-equiv="Content-Security-Policy" content="${CUSTOM_GAME_CSP}">` : ""}
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>html,body{margin:0;height:100%;background:transparent;overflow:hidden}canvas{display:block;width:100%;height:100%;touch-action:none;user-select:none;-webkit-user-select:none;outline:none}</style>
</head><body><canvas id="c" tabindex="0"></canvas>
<script>${boot}</script>
<script>${RUNTIME}</script>
</body></html>`;
}

